import { Scene, TranscriptItem, TrackedObject } from '../components/AnalysisPanel';

/**
 * Trigger a browser download of a string content as a file
 */
export const downloadFile = (content: string, fileName: string, contentType: string) => {
    const a = document.createElement('a');
    const file = new Blob([content], { type: contentType });
    a.href = URL.createObjectURL(file);
    a.download = fileName;
    a.click();
    URL.revokeObjectURL(a.href);
};

/**
 * Export analysis data to JSON
 */
export const exportToJson = (data: any, fileName: string) => {
    const jsonString = JSON.stringify(data, null, 2);
    downloadFile(jsonString, fileName, 'application/json');
};

/**
 * Export analysis data to CSV
 */
export const exportToCsv = (data: any[], headers: string[], fileName: string) => {
    if (!data || !data.length) return;

    const csvContent = [
        headers.join(','),
        ...data.map(row =>
            headers.map(header => {
                const value = row[header] ?? '';
                // Escape quotes and wrap in quotes if contains comma
                const stringValue = String(value).replace(/"/g, '""');
                return stringValue.includes(',') ? `"${stringValue}"` : stringValue;
            }).join(',')
        )
    ].join('\n');

    downloadFile(csvContent, fileName, 'text/csv');
};

/**
 * Formats scenes for CSV export
 */
export const scenesToCsv = (scenes: Scene[]) => {
    return scenes.map(s => ({
        timestamp: s.timestamp,
        timecode: formatTimestamp(s.timestamp),
        description: s.description
    }));
};

/**
 * Formats transcripts for CSV export
 */
export const transcriptsToCsv = (transcripts: TranscriptItem[]) => {
    return transcripts.map(t => ({
        startTime: t.startTime,
        endTime: t.endTime,
        start_timecode: formatTimestamp(t.startTime),
        end_timecode: formatTimestamp(t.endTime),
        text: t.text
    }));
};

/**
 * Utility to format seconds to HH:MM:SS
 */
const formatTimestamp = (seconds: number): string => {
    const h = Math.floor(seconds / 3600);
    const m = Math.floor((seconds % 3600) / 60);
    const s = Math.floor(seconds % 60);
    const ms = Math.floor((seconds % 1) * 100);
    return `${h.toString().padStart(2, '0')}:${m.toString().padStart(2, '0')}:${s.toString().padStart(2, '0')}.${ms.toString().padStart(2, '0')}`;
};

